-- =========================================================
-- 8. MASSA TRANSACIONAL: 600 VENDAS / 3 DIAS (200 por dia)
--    150 deliveries (50 por dia), com itens, pagamentos e comandas.
--    - Cada venda fica no caixa do seu turno (6h–14h / 14h–22h) e é feita por funcionário do turno.
--    - ~90% dos pagamentos digitais; delivery nunca é pago em dinheiro (RN16).
--    - Delivery: vendas com MOD(v,4)=2; WhatsApp (taxa R$ 4,00) e aplicativo (taxa da plataforma).
--    - 1 em cada 10 vendas de balcão nasce de uma comanda (60 comandas fechadas).
-- =========================================================
DELIMITER $$
DROP PROCEDURE IF EXISTS GERAR_MASSA_VENDAS $$
CREATE PROCEDURE GERAR_MASSA_VENDAS()
BEGIN
  DECLARE v INT DEFAULT 1;
  DECLARE v_dia INT;
  DECLARE v_idx INT;
  DECLARE v_turno INT;
  DECLARE v_produto INT;
  DECLARE v_cliente INT;
  DECLARE v_func INT;
  DECLARE v_caixa INT;
  DECLARE v_comanda INT;
  DECLARE v_venda INT;
  DECLARE v_qt DECIMAL(10,3);
  DECLARE v_preco DECIMAL(10,2);
  DECLARE v_desc DECIMAL(10,2);
  DECLARE v_total DECIMAL(10,2);
  DECLARE v_metade DECIMAL(10,2);
  DECLARE v_data DATETIME;
  DECLARE v_canal VARCHAR(10);
  DECLARE v_forma VARCHAR(20);
  DECLARE v_origem VARCHAR(20);

  WHILE v <= 600 DO
    SET v_dia   = FLOOR((v - 1) / 200);
    SET v_idx   = MOD(v - 1, 200);
    SET v_turno = IF(v_idx < 100, 1, 2);
    SET v_canal = IF(v > 1 AND MOD(v,4) = 2, 'DELIVERY', 'BALCAO');
    SET v_produto = IF(v BETWEEN 2 AND 21, 4, MOD(v - 1, 20) + 1);
    SET v_cliente = IF(MOD(v,4) = 0, NULL, MOD(v - 1, 20) + 1);
    SET v_func  = IF(v = 1, 1,
                  IF(v_turno = 1, ELT(MOD(v,5)+1, 1,2,3,7,4), ELT(MOD(v,4)+1, 8,9,10,11)));
    SET v_caixa = IF(v = 1, 5, v_dia * 2 + v_turno);
    SET v_qt = CASE WHEN v_produto = 1 THEN 0.300 WHEN MOD(v,5) = 0 THEN 2.000 ELSE 1.000 END;
    SELECT VL_PRECO_VENDA INTO v_preco FROM PRODUTO WHERE ID_PRODUTO = v_produto;
    SET v_desc  = IF(MOD(v,50) = 0 AND v_canal = 'BALCAO', 1.00, 0.00);
    SET v_total = ROUND(v_preco * v_qt, 2) - v_desc;
    SET v_data  = IF(v = 1, TIMESTAMP(@D2, '10:35:00'),
                  TIMESTAMP(DATE_ADD(@D0, INTERVAL v_dia DAY),
                            MAKETIME(IF(v_turno = 1, 6, 14) + MOD(v_idx, 8), MOD(v * 7, 60), 0)));

    -- Cesta repetida (coxinha + café) nas vendas 2 a 21: dá volume mínimo para a G29.
    IF v BETWEEN 2 AND 21 THEN
      SET v_total = v_total + 4.00;
    END IF;

    -- A venda 1 liquida a comanda 1 (valor = soma dos itens da comanda).
    IF v = 1 THEN
      SELECT SUM(QT_QUANTIDADE * VL_UNITARIO) INTO v_total FROM ITEM_COMANDA WHERE ID_COMANDA = 1;
      SET v_desc = 0.00;
    END IF;

    -- Forma de pagamento (~90% digital); delivery nunca em dinheiro.
    SET v_forma = CASE
      WHEN MOD(v,40) < 4  THEN 'DINHEIRO'
      WHEN MOD(v,40) < 18 THEN 'PIX'
      WHEN MOD(v,40) < 30 THEN 'DEBITO'
      WHEN MOD(v,40) < 38 THEN 'CREDITO'
      WHEN MOD(v,40) = 38 THEN 'VALE_ALIMENTACAO'
      ELSE 'VALE_REFEICAO' END;
    IF v_canal = 'DELIVERY' AND v_forma = 'DINHEIRO' THEN
      SET v_forma = 'PIX';
    END IF;

    -- Comanda associada (venda 1 usa a comanda 1; 1 em cada 10 vendas de balcão cria uma comanda).
    SET v_comanda = NULL;
    IF v = 1 THEN
      SET v_comanda = 1;
    ELSEIF MOD(v,10) = 3 THEN
      INSERT INTO COMANDA (NR_COMANDA,ID_CLIENTE,ID_FUNCIONARIO,TP_STATUS,DT_ABERTURA,DT_FECHAMENTO)
      VALUES (MOD(v,40) + 11, v_cliente, v_func, 'FECHADA', DATE_SUB(v_data, INTERVAL 25 MINUTE), v_data);
      SET v_comanda = LAST_INSERT_ID();
      INSERT INTO ITEM_COMANDA (ID_COMANDA,ID_PRODUTO,VL_UNITARIO,QT_QUANTIDADE)
      VALUES (v_comanda, v_produto, v_preco, v_qt);
      IF v BETWEEN 2 AND 21 THEN
        INSERT INTO ITEM_COMANDA (ID_COMANDA,ID_PRODUTO,VL_UNITARIO,QT_QUANTIDADE)
        VALUES (v_comanda, 12, 4.00, 1.000);
      END IF;
    END IF;

    INSERT INTO VENDA (ID_CAIXA,ID_FUNCIONARIO,ID_CLIENTE,ID_COMANDA,TP_CANAL,
                       VL_RECEBIDO,VL_TROCO,VL_DESCONTO,DT_VENDA,TP_STATUS,CD_CUPOM_FISCAL,VL_TOTAL)
    VALUES (v_caixa, v_func, v_cliente, v_comanda, v_canal,
            v_total, 0, v_desc, v_data, 'CONCLUIDA',
            CONCAT('CF-2026-', LPAD(v,6,'0')), v_total);
    SET v_venda = LAST_INSERT_ID();

    IF v = 1 THEN
      INSERT INTO ITEM_VENDA (ID_VENDA,ID_PRODUTO,QT_QUANTIDADE,VL_UNITARIO,VL_DESCONTO_ITEM)
      SELECT v_venda, ID_PRODUTO, QT_QUANTIDADE, VL_UNITARIO, 0
      FROM ITEM_COMANDA WHERE ID_COMANDA = 1;
    ELSE
      INSERT INTO ITEM_VENDA (ID_VENDA,ID_PRODUTO,QT_QUANTIDADE,VL_UNITARIO,VL_DESCONTO_ITEM)
      VALUES (v_venda, v_produto, v_qt, v_preco, v_desc);
      IF v BETWEEN 2 AND 21 THEN
        INSERT INTO ITEM_VENDA (ID_VENDA,ID_PRODUTO,QT_QUANTIDADE,VL_UNITARIO,VL_DESCONTO_ITEM)
        VALUES (v_venda, 12, 1.000, 4.00, 0);
      END IF;
    END IF;

    -- Pagamento: ~4% das vendas de balcão são divididas (metade dinheiro, metade PIX) — RN14.
    IF MOD(v,25) = 7 AND v_canal = 'BALCAO' AND v > 1 THEN
      SET v_metade = ROUND(v_total / 2, 2);
      INSERT INTO PAGAMENTO_VENDA (ID_VENDA,VL_PAGO,TP_FORMA_PAGAMENTO)
      VALUES (v_venda, v_metade, 'DINHEIRO'), (v_venda, v_total - v_metade, 'PIX');
    ELSE
      INSERT INTO PAGAMENTO_VENDA (ID_VENDA,VL_PAGO,TP_FORMA_PAGAMENTO)
      VALUES (v_venda, v_total, v_forma);
    END IF;

    -- Delivery: 50 por dia; tempo de rota de 18 a 52 minutos (alguns fora da meta de 40 min).
