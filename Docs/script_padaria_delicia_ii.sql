  CONSTRAINT CK_DOCUMENTO_TIPO CHECK (TP_DOCUMENTO IN
    ('FICHA_TECNICA','LAUDO_BOMBEIRO','LAUDO_SANITARIO','ALVARA_FUNCIONAMENTO','CODIGO_DEFESA_CONSUMIDOR')),
