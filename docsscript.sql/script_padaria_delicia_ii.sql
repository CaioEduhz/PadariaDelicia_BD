-- G25 — Em quais horários as comandas são abertas e qual é a permanência média?
-- Atende: P1 (controle do fluxo de entrada e saída de clientes).
SELECT HOUR(DT_ABERTURA) AS HORA,
       COUNT(*) AS COMANDAS_ABERTAS,
       ROUND(AVG(CASE WHEN DT_FECHAMENTO IS NOT NULL
          THEN TIMESTAMPDIFF(MINUTE,DT_ABERTURA,DT_FECHAMENTO) END),1)
          AS PERMANENCIA_MEDIA_MIN
FROM COMANDA
GROUP BY HOUR(DT_ABERTURA)
ORDER BY HORA;

-- G26 — Existem comandas em que o valor consumido é maior que o valor cobrado?
-- Atende: P2 (clientes que saem sem pagar); VL_TOTAL já representa o valor final cobrado.
SELECT cm.ID_COMANDA,cm.NR_COMANDA,cm.DT_ABERTURA,cm.TP_STATUS,
       f.NM_FUNCIONARIO,
       SUM(ic.QT_QUANTIDADE * ic.VL_UNITARIO) AS VALOR_CONSUMIDO,
       COALESCE(MAX(v.VL_TOTAL),0) AS VALOR_COBRADO,
       SUM(ic.QT_QUANTIDADE * ic.VL_UNITARIO)
         - COALESCE(MAX(v.VL_TOTAL),0) AS DIFERENCA
FROM COMANDA cm
JOIN ITEM_COMANDA ic ON ic.ID_COMANDA = cm.ID_COMANDA
JOIN FUNCIONARIO f ON f.ID_FUNCIONARIO = cm.ID_FUNCIONARIO
LEFT JOIN VENDA v
  ON v.ID_COMANDA = cm.ID_COMANDA AND v.TP_STATUS = 'CONCLUIDA'
WHERE cm.DT_ABERTURA < NOW() - INTERVAL 3 HOUR
GROUP BY cm.ID_COMANDA,cm.NR_COMANDA,cm.DT_ABERTURA,cm.TP_STATUS,f.NM_FUNCIONARIO
HAVING DIFERENCA > 0.01
ORDER BY DIFERENCA DESC;

-- G27 — Qual é a cobertura de comandas e de cupom fiscal nas vendas presenciais?
-- Atende: P3 (reduzir gestão informal); considera BALCAO e COMANDA como atendimento presencial.
SELECT DATE(DT_VENDA) AS DIA,
       SUM(CASE WHEN TP_CANAL IN ('BALCAO','COMANDA') THEN 1 ELSE 0 END)
         AS VENDAS_PRESENCIAIS,
       ROUND(100.0 * SUM(CASE WHEN TP_CANAL IN ('BALCAO','COMANDA')
                                  AND ID_COMANDA IS NOT NULL THEN 1 ELSE 0 END)
         / NULLIF(SUM(CASE WHEN TP_CANAL IN ('BALCAO','COMANDA') THEN 1 ELSE 0 END),0),1)
         AS PCT_COM_COMANDA,
       ROUND(100.0 * SUM(CASE WHEN CD_CUPOM_FISCAL IS NOT NULL THEN 1 ELSE 0 END)
         / NULLIF(COUNT(*),0),1) AS PCT_COM_CUPOM
FROM VENDA
WHERE TP_STATUS = 'CONCLUIDA'
GROUP BY DATE(DT_VENDA)
ORDER BY DIA;

-- G28 — Qual é a quantidade vendida por produto e dia da semana?
-- Atende: base histórica para previsão de demanda com IA/séries temporais.
SELECT DATE(v.DT_VENDA) AS DIA,
       DAYOFWEEK(v.DT_VENDA) AS DIA_SEMANA,
       i.ID_PRODUTO,
       SUM(i.QT_QUANTIDADE) AS QT_VENDIDA
FROM ITEM_VENDA i
JOIN VENDA v ON v.ID_VENDA = i.ID_VENDA
WHERE v.TP_STATUS = 'CONCLUIDA'
GROUP BY DATE(v.DT_VENDA),DAYOFWEEK(v.DT_VENDA),i.ID_PRODUTO
ORDER BY i.ID_PRODUTO,DIA;

-- G29 — Quais pares de produtos aparecem juntos na mesma venda?
-- Atende: recomendação de produtos e análise de cesta de compras.
SELECT a.ID_PRODUTO AS PRODUTO_A,
       b.ID_PRODUTO AS PRODUTO_B,
       COUNT(*) AS VENDAS_EM_CONJUNTO
FROM ITEM_VENDA a
JOIN ITEM_VENDA b
  ON b.ID_VENDA = a.ID_VENDA
 AND a.ID_PRODUTO < b.ID_PRODUTO
JOIN VENDA v ON v.ID_VENDA = a.ID_VENDA
WHERE v.TP_STATUS = 'CONCLUIDA'
GROUP BY a.ID_PRODUTO,b.ID_PRODUTO
HAVING COUNT(*) >= 10
ORDER BY VENDAS_EM_CONJUNTO DESC
LIMIT 50;

-- G30 — Como os clientes se classificam pela recência, frequência e valor (RFM)?
-- Atende: segmentação de clientes e identificação de risco de abandono.
WITH RFM_BASE AS (
    SELECT ID_CLIENTE,
           DATEDIFF(CURDATE(),DATE(MAX(DT_VENDA))) AS RECENCIA_DIAS,
           COUNT(*) AS FREQUENCIA,
           SUM(VL_TOTAL) AS VALOR
    FROM VENDA
    WHERE TP_STATUS = 'CONCLUIDA' AND ID_CLIENTE IS NOT NULL
    GROUP BY ID_CLIENTE
)
SELECT ID_CLIENTE,RECENCIA_DIAS,FREQUENCIA,VALOR,
       NTILE(5) OVER (ORDER BY RECENCIA_DIAS DESC) AS NOTA_R,
       NTILE(5) OVER (ORDER BY FREQUENCIA) AS NOTA_F,
       NTILE(5) OVER (ORDER BY VALOR) AS NOTA_M
FROM RFM_BASE
ORDER BY ID_CLIENTE;

-- G31 — Existem fechamentos de caixa com diferença estatisticamente atípica (z-score >= 2)?
-- Atende: detecção de anomalias com IA/estatística; requer variação nos valores de caixa.
WITH ESTATISTICAS AS (
    SELECT AVG(VL_DIFERENCA) AS MEDIA,
           STDDEV_POP(VL_DIFERENCA) AS DESVIO
    FROM CAIXA
    WHERE TP_STATUS = 'FECHADO'
)
SELECT c.ID_CAIXA,c.DT_FECHAMENTO,c.ID_FUNCIONARIO_FECHAMENTO,
       c.VL_DIFERENCA,
       ROUND((c.VL_DIFERENCA - e.MEDIA) / NULLIF(e.DESVIO,0),2) AS Z_SCORE
FROM CAIXA c
CROSS JOIN ESTATISTICAS e
WHERE c.TP_STATUS = 'FECHADO'
  AND e.DESVIO > 0
  AND ABS(c.VL_DIFERENCA - e.MEDIA) >= 2 * e.DESVIO
ORDER BY ABS(c.VL_DIFERENCA - e.MEDIA) DESC;

