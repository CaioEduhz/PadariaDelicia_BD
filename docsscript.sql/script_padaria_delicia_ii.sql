-- G01 — Qual foi o faturamento, o volume de vendas e o ticket médio por dia?
-- Atende: KPI de faturamento total, volume de vendas e ticket médio.
SELECT DATE(DT_VENDA) AS DIA,
       COUNT(*) AS QTD_VENDAS,
       SUM(VL_TOTAL) AS FATURAMENTO,
       ROUND(SUM(VL_TOTAL) / NULLIF(COUNT(*),0),2) AS TICKET_MEDIO
FROM VENDA
WHERE TP_STATUS = 'CONCLUIDA'
GROUP BY DATE(DT_VENDA)
ORDER BY DIA;

-- G02 — Qual foi o fluxo de caixa diário, considerando vendas e contas pagas?
-- Atende: KPI de fluxo de caixa e acompanhamento de entradas e saídas.
WITH ENTRADAS AS (
    SELECT DATE(DT_VENDA) AS DIA, SUM(VL_TOTAL) AS VALOR
    FROM VENDA WHERE TP_STATUS = 'CONCLUIDA'
    GROUP BY DATE(DT_VENDA)
),
SAIDAS AS (
    SELECT DT_PAGAMENTO AS DIA, SUM(VL_VALOR) AS VALOR
    FROM CONTA_PAGAR WHERE DT_PAGAMENTO IS NOT NULL
    GROUP BY DT_PAGAMENTO
),
DIAS AS (
    SELECT DIA FROM ENTRADAS
    UNION
    SELECT DIA FROM SAIDAS
)
SELECT d.DIA,
       COALESCE(e.VALOR,0) AS ENTRADAS,
       COALESCE(s.VALOR,0) AS SAIDAS,
       COALESCE(e.VALOR,0) - COALESCE(s.VALOR,0) AS SALDO,
       SUM(COALESCE(e.VALOR,0) - COALESCE(s.VALOR,0))
         OVER (ORDER BY d.DIA) AS SALDO_ACUMULADO
FROM DIAS d
LEFT JOIN ENTRADAS e ON e.DIA = d.DIA
LEFT JOIN SAIDAS s ON s.DIA = d.DIA
ORDER BY d.DIA;

-- G03 — Quais foram as despesas por mês, separando contas pagas e compras?
-- Atende: KPI de despesas. Não somar as duas origens, pois uma compra pode gerar boleto em CONTA_PAGAR.
SELECT DATE_FORMAT(DT_PAGAMENTO,'%Y-%m') AS MES,
       'CONTAS_PAGAS' AS ORIGEM, SUM(VL_VALOR) AS TOTAL
FROM CONTA_PAGAR
WHERE DT_PAGAMENTO IS NOT NULL
GROUP BY DATE_FORMAT(DT_PAGAMENTO,'%Y-%m')
UNION ALL
SELECT DATE_FORMAT(DT_COMPRA,'%Y-%m') AS MES,
       'COMPRAS' AS ORIGEM, SUM(VL_TOTAL) AS TOTAL
FROM COMPRA
GROUP BY DATE_FORMAT(DT_COMPRA,'%Y-%m')
ORDER BY MES, ORIGEM;

-- G04 — Quais contas a pagar estão em aberto ou vencidas?
-- Atende: KPI de contas vencidas e controle de compromissos financeiros.
SELECT f.NM_FORNECEDOR, cp.DS_DESCRICAO, cp.DT_VENCIMENTO,
       cp.VL_VALOR,
       CASE WHEN cp.DT_VENCIMENTO < CURDATE()
            THEN 'VENCIDA' ELSE 'A_VENCER' END AS SITUACAO
FROM CONTA_PAGAR cp
JOIN FORNECEDOR f ON f.ID_FORNECEDOR = cp.ID_FORNECEDOR
WHERE cp.DT_PAGAMENTO IS NULL
  AND cp.TP_STATUS IN ('ABERTA','VENCIDA')
ORDER BY cp.DT_VENCIMENTO;

-- G05 — Quais são os produtos mais vendidos por quantidade e faturamento?
-- Atende: KPI de produtos mais vendidos e planejamento de compras/produção.
SELECT p.NM_PRODUTO,
       SUM(i.QT_QUANTIDADE) AS QT_VENDIDA,
       SUM(i.QT_QUANTIDADE * i.VL_UNITARIO - i.VL_DESCONTO_ITEM) AS FATURAMENTO
FROM ITEM_VENDA i
JOIN VENDA v ON v.ID_VENDA = i.ID_VENDA
JOIN PRODUTO p ON p.ID_PRODUTO = i.ID_PRODUTO
WHERE v.TP_STATUS = 'CONCLUIDA'
GROUP BY p.ID_PRODUTO,p.NM_PRODUTO
ORDER BY QT_VENDIDA DESC
LIMIT 10;

-- G06 — Qual é a taxa de cancelamento de vendas por mês?
-- Atende: KPI de taxa de cancelamento de vendas.
SELECT DATE_FORMAT(DT_VENDA,'%Y-%m') AS MES,
       COUNT(*) AS TOTAL_VENDAS,
       SUM(CASE WHEN TP_STATUS = 'CANCELADA' THEN 1 ELSE 0 END) AS CANCELADAS,
       ROUND(100.0 * SUM(CASE WHEN TP_STATUS = 'CANCELADA' THEN 1 ELSE 0 END)
             / NULLIF(COUNT(*),0),2) AS PCT_CANCELAMENTO
FROM VENDA
GROUP BY DATE_FORMAT(DT_VENDA,'%Y-%m')
ORDER BY MES;

-- G07 — Qual é o desempenho de cada canal de venda?
-- Atende: KPI de vendas, faturamento e ticket médio por canal.
SELECT TP_CANAL, COUNT(*) AS QTD_VENDAS,
       SUM(VL_TOTAL) AS FATURAMENTO,
       ROUND(AVG(VL_TOTAL),2) AS TICKET_MEDIO
FROM VENDA
WHERE TP_STATUS = 'CONCLUIDA'
GROUP BY TP_CANAL
ORDER BY FATURAMENTO DESC;

-- G08 — Qual é a margem bruta estimada por produto?
-- Atende: KPI de margem bruta. Usa VL_CUSTO atual, portanto é uma estimativa histórica.
SELECT p.NM_PRODUTO,
       SUM(i.QT_QUANTIDADE * (i.VL_UNITARIO - COALESCE(p.VL_CUSTO,0))
           - i.VL_DESCONTO_ITEM) AS MARGEM_BRUTA,
       ROUND(100 * SUM(i.QT_QUANTIDADE * (i.VL_UNITARIO - COALESCE(p.VL_CUSTO,0))
           - i.VL_DESCONTO_ITEM)
           / NULLIF(SUM(i.QT_QUANTIDADE * i.VL_UNITARIO),0),1) AS PCT_MARGEM
FROM ITEM_VENDA i
JOIN VENDA v ON v.ID_VENDA = i.ID_VENDA
JOIN PRODUTO p ON p.ID_PRODUTO = i.ID_PRODUTO
WHERE v.TP_STATUS = 'CONCLUIDA'
GROUP BY p.ID_PRODUTO,p.NM_PRODUTO
ORDER BY MARGEM_BRUTA DESC;

-- G09 — Quais produtos e matérias-primas estão abaixo do estoque mínimo?
-- Atende: P4 (controle de estoque manual) e KPI de estoque abaixo do mínimo.
SELECT 'PRODUTO' AS TIPO, NM_PRODUTO AS NOME,
       QT_ESTOQUE, QT_ESTOQUE_MINIMO,
       IN_PRODUTO_ESSENCIAL AS ESSENCIAL
FROM PRODUTO
WHERE IN_ATIVO = TRUE AND QT_ESTOQUE <= QT_ESTOQUE_MINIMO
UNION ALL
SELECT 'MATERIA_PRIMA', NM_MATERIA_PRIMA,
       QT_ESTOQUE, QT_ESTOQUE_MINIMO, FALSE
FROM MATERIA_PRIMA
WHERE QT_ESTOQUE <= QT_ESTOQUE_MINIMO
ORDER BY ESSENCIAL DESC, QT_ESTOQUE ASC;

-- G10 — Qual é o índice de ruptura dos produtos ativos?
-- Atende: P4 e KPI de produtos ativos sem estoque.
SELECT SUM(CASE WHEN QT_ESTOQUE <= 0 THEN 1 ELSE 0 END) AS PRODUTOS_SEM_ESTOQUE,
       COUNT(*) AS PRODUTOS_ATIVOS,
       ROUND(100.0 * SUM(CASE WHEN QT_ESTOQUE <= 0 THEN 1 ELSE 0 END)
             / NULLIF(COUNT(*),0),2) AS PCT_RUPTURA
FROM PRODUTO
WHERE IN_ATIVO = TRUE;

-- G11 — Qual é o giro e a cobertura estimada de estoque nos últimos 30 dias?
-- Atende: P4 e KPI de giro/cobertura. Estoque atual é usado como aproximação do estoque médio.
SELECT p.NM_PRODUTO, COALESCE(x.QT_VENDIDA,0) AS VENDIDO_30D,
       p.QT_ESTOQUE,
       ROUND(COALESCE(x.QT_VENDIDA,0) / NULLIF(p.QT_ESTOQUE,0),2) AS GIRO,
       ROUND(p.QT_ESTOQUE / NULLIF(COALESCE(x.QT_VENDIDA,0) / 30.0,0),1)
         AS DIAS_COBERTURA
FROM PRODUTO p
LEFT JOIN (
    SELECT i.ID_PRODUTO, SUM(i.QT_QUANTIDADE) AS QT_VENDIDA
    FROM ITEM_VENDA i
    JOIN VENDA v ON v.ID_VENDA = i.ID_VENDA
    WHERE v.TP_STATUS = 'CONCLUIDA'
      AND v.DT_VENDA >= CURDATE() - INTERVAL 30 DAY
    GROUP BY i.ID_PRODUTO
) x ON x.ID_PRODUTO = p.ID_PRODUTO
WHERE p.IN_ATIVO = TRUE
ORDER BY (GIRO IS NULL), GIRO DESC;

-- G12 — Qual é o custo médio de aquisição dos produtos e matérias-primas?
-- Atende: KPI de custo médio de aquisição e comparação de fornecedores.
SELECT COALESCE(p.NM_PRODUTO,m.NM_MATERIA_PRIMA) AS ITEM,
       ROUND(SUM(i.QT_QUANTIDADE * i.VL_UNITARIO)
             / NULLIF(SUM(i.QT_QUANTIDADE),0),2) AS CUSTO_MEDIO,
       MIN(i.VL_UNITARIO) AS MENOR_CUSTO,
       MAX(i.VL_UNITARIO) AS MAIOR_CUSTO
FROM ITEM_COMPRA i
LEFT JOIN PRODUTO p ON p.ID_PRODUTO = i.ID_PRODUTO
LEFT JOIN MATERIA_PRIMA m ON m.ID_MATERIA_PRIMA = i.ID_MATERIA_PRIMA
GROUP BY COALESCE(p.NM_PRODUTO,m.NM_MATERIA_PRIMA)
ORDER BY ITEM;

-- G13 — Qual é a participação de cada fornecedor no total comprado nos últimos 90 dias?
-- Atende: KPI de dependência/concentração de fornecedores.
SELECT f.NM_FORNECEDOR, SUM(c.VL_TOTAL) AS TOTAL_COMPRADO,
       ROUND(100 * SUM(c.VL_TOTAL)
             / NULLIF(SUM(SUM(c.VL_TOTAL)) OVER (),0),1) AS PCT_DO_TOTAL
FROM COMPRA c
JOIN FORNECEDOR f ON f.ID_FORNECEDOR = c.ID_FORNECEDOR
WHERE c.DT_COMPRA >= CURDATE() - INTERVAL 90 DAY
GROUP BY f.ID_FORNECEDOR,f.NM_FORNECEDOR
ORDER BY TOTAL_COMPRADO DESC;

-- G14 — Qual foi o volume produzido e o índice de perdas por mês e produto?
-- Atende: KPI de volume de produção e índice de perdas.
SELECT DATE_FORMAT(pr.DT_PRODUCAO,'%Y-%m') AS MES,
       p.NM_PRODUTO,
       SUM(pr.QT_PRODUZIDA) AS PRODUZIDO,
       SUM(pr.QT_PERDA) AS PERDAS,
       ROUND(100 * SUM(pr.QT_PERDA) / NULLIF(SUM(pr.QT_PRODUZIDA),0),2) AS PCT_PERDA
FROM PRODUCAO pr
JOIN PRODUTO p ON p.ID_PRODUTO = pr.ID_PRODUTO
GROUP BY DATE_FORMAT(pr.DT_PRODUCAO,'%Y-%m'),p.ID_PRODUTO,p.NM_PRODUTO
ORDER BY MES,PCT_PERDA DESC;

-- G15 — Qual é a produtividade de cada funcionário da produção?
-- Atende: KPI de produtividade por funcionário.
SELECT f.NM_FUNCIONARIO, f.TP_CARGO,
       COUNT(DISTINCT DATE(pr.DT_PRODUCAO)) AS DIAS_COM_PRODUCAO,
       SUM(pr.QT_PRODUZIDA) AS TOTAL_PRODUZIDO,
       ROUND(SUM(pr.QT_PRODUZIDA)
             / NULLIF(COUNT(DISTINCT DATE(pr.DT_PRODUCAO)),0),1) AS MEDIA_POR_DIA
FROM PRODUCAO pr
JOIN FUNCIONARIO f ON f.ID_FUNCIONARIO = pr.ID_FUNCIONARIO
GROUP BY f.ID_FUNCIONARIO,f.NM_FUNCIONARIO,f.TP_CARGO
ORDER BY TOTAL_PRODUZIDO DESC;

-- G16 — Qual é o custo estimado dos insumos usados na produção?
-- Atende: KPI de custo de produção, usando ficha técnica e custo médio de compra.
WITH CUSTO_MEDIO AS (
    SELECT ID_MATERIA_PRIMA,
           SUM(QT_QUANTIDADE * VL_UNITARIO) / NULLIF(SUM(QT_QUANTIDADE),0) AS CUSTO
    FROM ITEM_COMPRA
    WHERE ID_MATERIA_PRIMA IS NOT NULL
    GROUP BY ID_MATERIA_PRIMA
),
PRODUZIDO_30D AS (
    SELECT ID_PRODUTO,SUM(QT_PRODUZIDA) AS QT
    FROM PRODUCAO
    WHERE DT_PRODUCAO >= CURDATE() - INTERVAL 30 DAY
    GROUP BY ID_PRODUTO
)
SELECT p.NM_PRODUTO,
       ROUND(SUM(ft.QT_QUANTIDADE * cm.CUSTO),2) AS CUSTO_INSUMOS_UNIDADE,
       ROUND(p.VL_PRECO_VENDA - SUM(ft.QT_QUANTIDADE * cm.CUSTO),2) AS MARGEM_UNITARIA,
       ROUND(COALESCE(q.QT,0) * SUM(ft.QT_QUANTIDADE * cm.CUSTO),2) AS CUSTO_PRODUCAO_30D
FROM PRODUTO p
JOIN ITEM_FICHA_TECNICA ft ON ft.ID_PRODUTO = p.ID_PRODUTO
JOIN CUSTO_MEDIO cm ON cm.ID_MATERIA_PRIMA = ft.ID_MATERIA_PRIMA
LEFT JOIN PRODUZIDO_30D q ON q.ID_PRODUTO = p.ID_PRODUTO
GROUP BY p.ID_PRODUTO,p.NM_PRODUTO,p.VL_PRECO_VENDA,q.QT;

-- G17 — Qual é a recorrência, frequência e gasto médio dos clientes identificados?
-- Atende: KPIs de recorrência, frequência de compra e ticket por cliente (90 dias).
WITH COMPRAS_CLIENTE AS (
    SELECT ID_CLIENTE,COUNT(*) AS COMPRAS,SUM(VL_TOTAL) AS GASTO
    FROM VENDA
    WHERE TP_STATUS = 'CONCLUIDA'
      AND ID_CLIENTE IS NOT NULL
      AND DT_VENDA >= CURDATE() - INTERVAL 90 DAY
    GROUP BY ID_CLIENTE
)
SELECT COUNT(*) AS CLIENTES_IDENTIFICADOS,
       ROUND(100.0 * SUM(CASE WHEN COMPRAS > 1 THEN 1 ELSE 0 END)
             / NULLIF(COUNT(*),0),1) AS TAXA_RECORRENCIA,
       ROUND(AVG(COMPRAS),2) AS FREQUENCIA_MEDIA,
       ROUND(AVG(GASTO),2) AS GASTO_MEDIO_POR_CLIENTE
FROM COMPRAS_CLIENTE;

-- G18 — Quais clientes estão inativos há mais de 30 dias ou nunca compraram?
-- Atende: KPI de clientes inativos e ações de relacionamento/fidelização.
SELECT c.ID_CLIENTE,c.NM_CLIENTE,c.CD_TELEFONE,
       MAX(v.DT_VENDA) AS ULTIMA_COMPRA,
       CASE WHEN MAX(v.DT_VENDA) IS NULL THEN NULL
            ELSE DATEDIFF(CURDATE(),DATE(MAX(v.DT_VENDA))) END AS DIAS_SEM_COMPRAR
FROM CLIENTE c
LEFT JOIN VENDA v
  ON v.ID_CLIENTE = c.ID_CLIENTE AND v.TP_STATUS = 'CONCLUIDA'
GROUP BY c.ID_CLIENTE,c.NM_CLIENTE,c.CD_TELEFONE
HAVING MAX(v.DT_VENDA) IS NULL
    OR MAX(v.DT_VENDA) < CURDATE() - INTERVAL 30 DAY
ORDER BY DIAS_SEM_COMPRAR DESC;

-- G19 — Qual é o tempo médio de entrega, o percentual no prazo e os cancelamentos?
-- Atende: KPIs de tempo médio, entregas em até 40 minutos e cancelamento de delivery.
SELECT TP_CANAL_ORIGEM,
       COUNT(*) AS PEDIDOS,
       ROUND(AVG(CASE WHEN TP_STATUS = 'ENTREGUE'
          THEN TIMESTAMPDIFF(MINUTE,DT_SAIDA,DT_ENTREGA) END),1) AS TEMPO_MEDIO_MIN,
       ROUND(100.0 * SUM(CASE WHEN TP_STATUS = 'ENTREGUE'
          AND TIMESTAMPDIFF(MINUTE,DT_SAIDA,DT_ENTREGA) <= 40 THEN 1 ELSE 0 END)
          / NULLIF(SUM(CASE WHEN TP_STATUS = 'ENTREGUE' THEN 1 ELSE 0 END),0),1)
          AS PCT_NO_PRAZO,
       ROUND(100.0 * SUM(CASE WHEN TP_STATUS = 'CANCELADO' THEN 1 ELSE 0 END)
          / NULLIF(COUNT(*),0),1) AS PCT_CANCELADO
FROM DELIVERY
GROUP BY TP_CANAL_ORIGEM;

-- G20 — Qual é o volume mensal de encomendas, cancelamentos e sinais retidos?
-- Atende: KPIs de volume, cancelamento e não retirada de encomendas.
SELECT DATE_FORMAT(DT_RETIRADA_ENTREGA,'%Y-%m') AS MES,
       COUNT(*) AS VOLUME,
       SUM(CASE WHEN TP_STATUS = 'CANCELADA' THEN 1 ELSE 0 END) AS CANCELADAS,
       ROUND(100.0 * SUM(CASE WHEN TP_STATUS = 'CANCELADA' THEN 1 ELSE 0 END)
             / NULLIF(COUNT(*),0),1) AS PCT_CANCELAMENTO,
       SUM(CASE WHEN TP_STATUS = 'NAO_RETIRADA' THEN 1 ELSE 0 END) AS NAO_RETIRADAS,
       SUM(CASE WHEN TP_STATUS = 'NAO_RETIRADA' THEN VL_SINAL ELSE 0 END) AS SINAL_RETIDO
FROM ENCOMENDA
GROUP BY DATE_FORMAT(DT_RETIRADA_ENTREGA,'%Y-%m')
ORDER BY MES;

-- G21 — Qual é o faturamento e o ticket médio por funcionário?
-- Atende: KPI de faturamento por funcionário.
SELECT f.NM_FUNCIONARIO,f.TP_TURNO,
       COUNT(*) AS QTD_VENDAS,
       SUM(v.VL_TOTAL) AS FATURAMENTO,
       ROUND(AVG(v.VL_TOTAL),2) AS TICKET_MEDIO
FROM VENDA v
JOIN FUNCIONARIO f ON f.ID_FUNCIONARIO = v.ID_FUNCIONARIO
WHERE v.TP_STATUS = 'CONCLUIDA'
GROUP BY f.ID_FUNCIONARIO,f.NM_FUNCIONARIO,f.TP_TURNO
