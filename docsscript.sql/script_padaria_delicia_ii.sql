/* =====================================================================
   PADARIA DELICIA II — SCRIPT SQL COMPLETO
   SGBD: MySQL 8.0 | Engine: InnoDB | Charset: utf8mb4
   Cria 24 tabelas e uma massa inteiramente fictícia.
   Volume: 600 vendas em 3 dias (aprox. 200 atendimentos/dia) e
   150 deliveries (aprox. 50/dia), conforme o porte informado da padaria.
   Inclui variedade de status, pagamentos, clientes sem compras, estoque
   abaixo do mínimo, comandas e divergência de caixa. MySQL 8.0.
   ===================================================================== */

DROP DATABASE IF EXISTS PADARIA_DELICIA_II;
CREATE DATABASE PADARIA_DELICIA_II
  DEFAULT CHARACTER SET utf8mb4
  DEFAULT COLLATE utf8mb4_0900_ai_ci;
USE PADARIA_DELICIA_II;

-- =========================================================
-- 1. TABELAS DE CADASTRO
-- =========================================================
CREATE TABLE IF NOT EXISTS CATEGORIA (
  ID_CATEGORIA INT AUTO_INCREMENT PRIMARY KEY,
  NM_CATEGORIA VARCHAR(60) NOT NULL,
  CONSTRAINT UK_CATEGORIA_NOME UNIQUE (NM_CATEGORIA)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS MATERIA_PRIMA (
  ID_MATERIA_PRIMA INT AUTO_INCREMENT PRIMARY KEY,
  NM_MATERIA_PRIMA VARCHAR(120) NOT NULL,
  CD_UNIDADE VARCHAR(5) NOT NULL,
  QT_ESTOQUE DECIMAL(10,3) NOT NULL DEFAULT 0,
  QT_ESTOQUE_MINIMO DECIMAL(10,3),
  CONSTRAINT CK_MP_ESTOQUE CHECK (QT_ESTOQUE >= 0),
  CONSTRAINT CK_MP_MINIMO CHECK (QT_ESTOQUE_MINIMO IS NULL OR QT_ESTOQUE_MINIMO >= 0)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS FORNECEDOR (
  ID_FORNECEDOR INT AUTO_INCREMENT PRIMARY KEY,
  NM_FORNECEDOR VARCHAR(150) NOT NULL,
  CD_CNPJ_CPF VARCHAR(14) NOT NULL,
  NM_CONTATO VARCHAR(120),
  CD_TELEFONE VARCHAR(20),
  DS_ENDERECO VARCHAR(255),
  CONSTRAINT UK_FORNECEDOR_CNPJCPF UNIQUE (CD_CNPJ_CPF)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS CLIENTE (
  ID_CLIENTE INT AUTO_INCREMENT PRIMARY KEY,
  NM_CLIENTE VARCHAR(120) NOT NULL,
  CD_TELEFONE VARCHAR(20),
  DT_CADASTRO DATE NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS FUNCIONARIO (
  ID_FUNCIONARIO INT AUTO_INCREMENT PRIMARY KEY,
  NM_FUNCIONARIO VARCHAR(120) NOT NULL,
  IN_ATIVO BOOLEAN NOT NULL DEFAULT TRUE,
  TP_TURNO VARCHAR(10) NOT NULL,
  DS_SENHA_HASH VARCHAR(255) NOT NULL,
  TP_CARGO VARCHAR(15) NOT NULL,
  CD_LOGIN VARCHAR(40) NOT NULL,
  CONSTRAINT UK_FUNCIONARIO_LOGIN UNIQUE (CD_LOGIN),
  CONSTRAINT CK_FUNCIONARIO_TURNO CHECK (TP_TURNO IN ('MANHA','TARDE','NOITE','MISTO'))
) ENGINE=InnoDB;

-- =========================================================
-- 2. PRODUTOS, RECEITAS E DOCUMENTOS
-- =========================================================
CREATE TABLE IF NOT EXISTS PRODUTO (
  ID_PRODUTO INT AUTO_INCREMENT PRIMARY KEY,
  ID_CATEGORIA INT NOT NULL,
  CD_PRODUTO VARCHAR(20) NOT NULL,
  NM_PRODUTO VARCHAR(120) NOT NULL,
  DS_PRODUTO TEXT,
  VL_PRECO_VENDA DECIMAL(10,2) NOT NULL,
  VL_CUSTO DECIMAL(10,2),
  CD_UNIDADE VARCHAR(5) NOT NULL,
  QT_ESTOQUE DECIMAL(10,3) NOT NULL DEFAULT 0,
  QT_ESTOQUE_MINIMO DECIMAL(10,3) NOT NULL DEFAULT 0,
  DT_VALIDADE DATE,
  IN_PRODUTO_ESSENCIAL BOOLEAN NOT NULL DEFAULT FALSE,
  IN_ATIVO BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT FK_PRODUTO_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIA(ID_CATEGORIA),
  CONSTRAINT UK_PRODUTO_CODIGO UNIQUE (CD_PRODUTO),
  CONSTRAINT CK_PRODUTO_PRECO CHECK (VL_PRECO_VENDA >= 0),
  CONSTRAINT CK_PRODUTO_CUSTO CHECK (VL_CUSTO IS NULL OR VL_CUSTO >= 0),
  CONSTRAINT CK_PRODUTO_ESTOQUE CHECK (QT_ESTOQUE >= 0 AND QT_ESTOQUE_MINIMO >= 0),
  INDEX IX_PRODUTO_NOME (NM_PRODUTO),
  INDEX IX_PRODUTO_CATEGORIA (ID_CATEGORIA)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ITEM_FICHA_TECNICA (
  ID_PRODUTO INT NOT NULL,
  ID_MATERIA_PRIMA INT NOT NULL,
  QT_QUANTIDADE DECIMAL(10,3) NOT NULL,
  PRIMARY KEY (ID_PRODUTO, ID_MATERIA_PRIMA),
  CONSTRAINT FK_FICHA_PRODUTO FOREIGN KEY (ID_PRODUTO) REFERENCES PRODUTO(ID_PRODUTO),
  CONSTRAINT FK_FICHA_MATERIA FOREIGN KEY (ID_MATERIA_PRIMA) REFERENCES MATERIA_PRIMA(ID_MATERIA_PRIMA),
  CONSTRAINT CK_FICHA_QUANTIDADE CHECK (QT_QUANTIDADE > 0)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS DOCUMENTO_REGULATORIO (
  ID_DOCUMENTO INT AUTO_INCREMENT PRIMARY KEY,
  TP_DOCUMENTO VARCHAR(30) NOT NULL,
  DS_ARQUIVO VARCHAR(255) NOT NULL,
  DT_EMISSAO DATE,
  DT_VALIDADE DATE,
  ID_PRODUTO INT,
  CONSTRAINT FK_DOCUMENTO_PRODUTO FOREIGN KEY (ID_PRODUTO) REFERENCES PRODUTO(ID_PRODUTO),
  INDEX IX_DOCUMENTO_PRODUTO (ID_PRODUTO),
  INDEX IX_DOCUMENTO_TIPO (TP_DOCUMENTO)
) ENGINE=InnoDB;

-- =========================================================
-- 3. COMPRAS, ITENS DE COMPRA E CONTAS A PAGAR
-- =========================================================
CREATE TABLE IF NOT EXISTS COMPRA (
  ID_COMPRA INT AUTO_INCREMENT PRIMARY KEY,
  ID_FORNECEDOR INT NOT NULL,
  DT_COMPRA DATE NOT NULL,
  CD_NOTA_FISCAL VARCHAR(44),
  VL_TOTAL DECIMAL(10,2) NOT NULL DEFAULT 0,
  CONSTRAINT FK_COMPRA_FORNECEDOR FOREIGN KEY (ID_FORNECEDOR) REFERENCES FORNECEDOR(ID_FORNECEDOR),
  CONSTRAINT UK_COMPRA_NOTA_FORNECEDOR UNIQUE (ID_FORNECEDOR, CD_NOTA_FISCAL),
  CONSTRAINT CK_COMPRA_TOTAL CHECK (VL_TOTAL >= 0)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ITEM_COMPRA (
  ID_ITEM INT AUTO_INCREMENT PRIMARY KEY,
  ID_COMPRA INT NOT NULL,
  ID_PRODUTO INT,
  ID_MATERIA_PRIMA INT,
  QT_QUANTIDADE DECIMAL(10,3) NOT NULL,
  VL_UNITARIO DECIMAL(10,2) NOT NULL,
  CONSTRAINT FK_ITEM_COMPRA_COMPRA FOREIGN KEY (ID_COMPRA) REFERENCES COMPRA(ID_COMPRA),
  CONSTRAINT FK_ITEM_COMPRA_PRODUTO FOREIGN KEY (ID_PRODUTO) REFERENCES PRODUTO(ID_PRODUTO),
  CONSTRAINT FK_ITEM_COMPRA_MATERIA FOREIGN KEY (ID_MATERIA_PRIMA) REFERENCES MATERIA_PRIMA(ID_MATERIA_PRIMA),
  CONSTRAINT CK_ITEM_COMPRA_ORIGEM CHECK ((ID_PRODUTO IS NOT NULL AND ID_MATERIA_PRIMA IS NULL) OR (ID_PRODUTO IS NULL AND ID_MATERIA_PRIMA IS NOT NULL)),
  CONSTRAINT CK_ITEM_COMPRA_VALORES CHECK (QT_QUANTIDADE > 0 AND VL_UNITARIO >= 0),
  INDEX IX_ITEM_COMPRA_COMPRA (ID_COMPRA)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS CONTA_PAGAR (
  ID_CONTA_PAGAR INT AUTO_INCREMENT PRIMARY KEY,
  ID_FORNECEDOR INT NOT NULL,
  VL_VALOR DECIMAL(10,2) NOT NULL,
  TP_STATUS VARCHAR(30) NOT NULL,
  DT_PAGAMENTO DATE,
  DS_DESCRICAO VARCHAR(255),
  DT_VENCIMENTO DATE NOT NULL,
  CONSTRAINT FK_CONTA_PAGAR_FORNECEDOR FOREIGN KEY (ID_FORNECEDOR) REFERENCES FORNECEDOR(ID_FORNECEDOR),
  CONSTRAINT CK_CONTA_PAGAR_VALOR CHECK (VL_VALOR > 0),
  CONSTRAINT CK_CONTA_PAGAR_STATUS CHECK (TP_STATUS IN ('ABERTA','PAGA','VENCIDA','CANCELADA'))
) ENGINE=InnoDB;

-- =========================================================
-- 4. PRODUÇÃO E ATENDIMENTO
-- =========================================================
CREATE TABLE IF NOT EXISTS PRODUCAO (
  ID_PRODUCAO INT AUTO_INCREMENT PRIMARY KEY,
  ID_PRODUTO INT NOT NULL,
  ID_FUNCIONARIO INT NOT NULL,
  QT_PRODUZIDA DECIMAL(10,3) NOT NULL,
  DT_PRODUCAO DATETIME NOT NULL,
  QT_PERDA DECIMAL(10,3) NOT NULL DEFAULT 0,
  CONSTRAINT FK_PRODUCAO_PRODUTO FOREIGN KEY (ID_PRODUTO) REFERENCES PRODUTO(ID_PRODUTO),
  CONSTRAINT FK_PRODUCAO_FUNCIONARIO FOREIGN KEY (ID_FUNCIONARIO) REFERENCES FUNCIONARIO(ID_FUNCIONARIO),
  CONSTRAINT CK_PRODUCAO_QT CHECK (QT_PRODUZIDA > 0 AND QT_PERDA >= 0 AND QT_PERDA <= QT_PRODUZIDA)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS COMANDA (
  ID_COMANDA INT AUTO_INCREMENT PRIMARY KEY,
  NR_COMANDA INT NOT NULL,
  ID_CLIENTE INT,
  ID_FUNCIONARIO INT NOT NULL,
  TP_STATUS VARCHAR(30) NOT NULL,
  DT_ABERTURA DATETIME NOT NULL,
  DT_FECHAMENTO DATETIME,
  NR_ABERTA INT GENERATED ALWAYS AS
    (CASE WHEN TP_STATUS = 'ABERTA' THEN NR_COMANDA END) STORED,
  CONSTRAINT FK_COMANDA_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE(ID_CLIENTE),
  CONSTRAINT FK_COMANDA_FUNCIONARIO FOREIGN KEY (ID_FUNCIONARIO) REFERENCES FUNCIONARIO(ID_FUNCIONARIO),
  CONSTRAINT CK_COMANDA_STATUS CHECK (TP_STATUS IN ('ABERTA','FECHADA','CANCELADA')),
  CONSTRAINT UQ_COMANDA_NR_ABERTA UNIQUE (NR_ABERTA)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ITEM_COMANDA (
  ID_ITEM INT AUTO_INCREMENT PRIMARY KEY,
  ID_COMANDA INT NOT NULL,
  ID_PRODUTO INT NOT NULL,
  VL_UNITARIO DECIMAL(10,2) NOT NULL,
  QT_QUANTIDADE DECIMAL(10,3) NOT NULL,
  CONSTRAINT FK_ITEM_COMANDA_COMANDA FOREIGN KEY (ID_COMANDA) REFERENCES COMANDA(ID_COMANDA),
  CONSTRAINT FK_ITEM_COMANDA_PRODUTO FOREIGN KEY (ID_PRODUTO) REFERENCES PRODUTO(ID_PRODUTO),
  CONSTRAINT CK_ITEM_COMANDA_VALORES CHECK (VL_UNITARIO >= 0 AND QT_QUANTIDADE > 0)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ENCOMENDA (
  ID_ENCOMENDA INT AUTO_INCREMENT PRIMARY KEY,
  ID_CLIENTE INT NOT NULL,
  TP_STATUS VARCHAR(30) NOT NULL,
  DT_RETIRADA_ENTREGA DATETIME NOT NULL,
  VL_SINAL DECIMAL(10,2) NOT NULL,
  DS_PERSONALIZACAO VARCHAR(255),
  VL_TOTAL DECIMAL(10,2) NOT NULL,
  CONSTRAINT FK_ENCOMENDA_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE(ID_CLIENTE),
  CONSTRAINT CK_ENCOMENDA_VALORES CHECK (VL_SINAL >= 0 AND VL_TOTAL >= 0 AND VL_SINAL <= VL_TOTAL),
  CONSTRAINT CK_ENCOMENDA_STATUS CHECK (TP_STATUS IN ('ABERTA','EM_PRODUCAO','PRONTA','RETIRADA','CANCELADA','NAO_RETIRADA'))
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ITEM_ENCOMENDA (
  ID_ITEM INT AUTO_INCREMENT PRIMARY KEY,
  ID_ENCOMENDA INT NOT NULL,
  ID_PRODUTO INT NOT NULL,
  QT_QUANTIDADE DECIMAL(10,3) NOT NULL,
  VL_UNITARIO DECIMAL(10,2) NOT NULL,
  CONSTRAINT FK_ITEM_ENCOMENDA_ENCOMENDA FOREIGN KEY (ID_ENCOMENDA) REFERENCES ENCOMENDA(ID_ENCOMENDA),
  CONSTRAINT FK_ITEM_ENCOMENDA_PRODUTO FOREIGN KEY (ID_PRODUTO) REFERENCES PRODUTO(ID_PRODUTO),
  CONSTRAINT CK_ITEM_ENCOMENDA_VALORES CHECK (QT_QUANTIDADE > 0 AND VL_UNITARIO >= 0)
) ENGINE=InnoDB;

-- =========================================================
-- 5. CAIXA, VENDAS, PAGAMENTOS E DELIVERY
-- =========================================================
CREATE TABLE IF NOT EXISTS CAIXA (
  ID_CAIXA INT AUTO_INCREMENT PRIMARY KEY,
  ID_FUNCIONARIO_ABERTURA INT NOT NULL,
  ID_FUNCIONARIO_FECHAMENTO INT,
  VL_ABERTURA DECIMAL(10,2) NOT NULL DEFAULT 0,
  DT_ABERTURA DATETIME NOT NULL,
  DT_FECHAMENTO DATETIME,
  TP_STATUS VARCHAR(20) NOT NULL,
  VL_TOTAL_SISTEMA DECIMAL(10,2) NOT NULL DEFAULT 0,
  VL_TOTAL_INFORMADO DECIMAL(10,2),
  VL_DIFERENCA DECIMAL(10,2),
  CONSTRAINT FK_CAIXA_FUNC_ABERTURA FOREIGN KEY (ID_FUNCIONARIO_ABERTURA) REFERENCES FUNCIONARIO(ID_FUNCIONARIO),
  CONSTRAINT FK_CAIXA_FUNC_FECHAMENTO FOREIGN KEY (ID_FUNCIONARIO_FECHAMENTO) REFERENCES FUNCIONARIO(ID_FUNCIONARIO),
  CONSTRAINT CK_CAIXA_STATUS CHECK (TP_STATUS IN ('ABERTO','FECHADO')),
  CONSTRAINT CK_CAIXA_VALORES CHECK (VL_ABERTURA >= 0 AND VL_TOTAL_SISTEMA >= 0)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS VENDA (
  ID_VENDA INT AUTO_INCREMENT PRIMARY KEY,
  ID_CAIXA INT NOT NULL,
  ID_FUNCIONARIO INT NOT NULL,
  ID_CLIENTE INT,
  ID_COMANDA INT,
  TP_CANAL VARCHAR(20) NOT NULL,
  VL_RECEBIDO DECIMAL(10,2) NOT NULL DEFAULT 0,
  VL_TROCO DECIMAL(10,2) NOT NULL DEFAULT 0,
  VL_DESCONTO DECIMAL(10,2) NOT NULL DEFAULT 0,
  DT_VENDA DATETIME NOT NULL,
  TP_STATUS VARCHAR(30) NOT NULL,
  CD_CUPOM_FISCAL VARCHAR(50),
  VL_TOTAL DECIMAL(10,2) NOT NULL,
  CONSTRAINT FK_VENDA_CAIXA FOREIGN KEY (ID_CAIXA) REFERENCES CAIXA(ID_CAIXA),
  CONSTRAINT FK_VENDA_FUNCIONARIO FOREIGN KEY (ID_FUNCIONARIO) REFERENCES FUNCIONARIO(ID_FUNCIONARIO),
  CONSTRAINT FK_VENDA_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE(ID_CLIENTE),
  CONSTRAINT FK_VENDA_COMANDA FOREIGN KEY (ID_COMANDA) REFERENCES COMANDA(ID_COMANDA),
  CONSTRAINT UK_VENDA_COMANDA UNIQUE (ID_COMANDA),
  CONSTRAINT UK_VENDA_CUPOM UNIQUE (CD_CUPOM_FISCAL),
  CONSTRAINT CK_VENDA_CANAL CHECK (TP_CANAL IN ('BALCAO','DELIVERY','COMANDA')),
  CONSTRAINT CK_VENDA_STATUS CHECK (TP_STATUS IN ('CONCLUIDA','CANCELADA','ESTORNADA')),
  CONSTRAINT CK_VENDA_VALORES CHECK (VL_RECEBIDO >= 0 AND VL_TROCO >= 0 AND VL_DESCONTO >= 0 AND VL_TOTAL >= 0),
  INDEX IX_VENDA_DATA (DT_VENDA),
  INDEX IX_VENDA_CAIXA (ID_CAIXA)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ITEM_VENDA (
  ID_ITEM INT AUTO_INCREMENT PRIMARY KEY,
  ID_VENDA INT NOT NULL,
  ID_PRODUTO INT NOT NULL,
  QT_QUANTIDADE DECIMAL(10,3) NOT NULL,
  VL_UNITARIO DECIMAL(10,2) NOT NULL,
  VL_DESCONTO_ITEM DECIMAL(10,2) NOT NULL DEFAULT 0,
  CONSTRAINT FK_ITEM_VENDA_VENDA FOREIGN KEY (ID_VENDA) REFERENCES VENDA(ID_VENDA),
  CONSTRAINT FK_ITEM_VENDA_PRODUTO FOREIGN KEY (ID_PRODUTO) REFERENCES PRODUTO(ID_PRODUTO),
  CONSTRAINT CK_ITEM_VENDA_VALORES CHECK (QT_QUANTIDADE > 0 AND VL_UNITARIO >= 0 AND VL_DESCONTO_ITEM >= 0)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS PAGAMENTO_VENDA (
  ID_PAGAMENTO INT AUTO_INCREMENT PRIMARY KEY,
  ID_VENDA INT NOT NULL,
  VL_PAGO DECIMAL(10,2) NOT NULL,
  TP_FORMA_PAGAMENTO VARCHAR(30) NOT NULL,
  CONSTRAINT FK_PAGAMENTO_VENDA FOREIGN KEY (ID_VENDA) REFERENCES VENDA(ID_VENDA),
  CONSTRAINT CK_PAGAMENTO_VALOR CHECK (VL_PAGO > 0),
  CONSTRAINT CK_PAGAMENTO_FORMA CHECK (TP_FORMA_PAGAMENTO IN ('DINHEIRO','PIX','DEBITO','CREDITO','VALE_ALIMENTACAO','VALE_REFEICAO'))
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS DELIVERY (
  ID_DELIVERY INT AUTO_INCREMENT PRIMARY KEY,
  ID_VENDA INT NOT NULL,
  DT_SAIDA DATETIME,
  DT_ENTREGA DATETIME,
  TP_STATUS VARCHAR(30) NOT NULL,
  DS_OBSERVACAO VARCHAR(255),
  DS_ENDERECO_ENTREGA VARCHAR(255) NOT NULL,
  TP_CANAL_ORIGEM VARCHAR(30) NOT NULL,
  VL_TAXA_ENTREGA DECIMAL(10,2) NOT NULL DEFAULT 0,
  CONSTRAINT FK_DELIVERY_VENDA FOREIGN KEY (ID_VENDA) REFERENCES VENDA(ID_VENDA),
  CONSTRAINT UK_DELIVERY_VENDA UNIQUE (ID_VENDA),
  CONSTRAINT CK_DELIVERY_STATUS CHECK (TP_STATUS IN ('PENDENTE','SAIU_PARA_ENTREGA','ENTREGUE','CANCELADO')),
  CONSTRAINT CK_DELIVERY_ORIGEM CHECK (TP_CANAL_ORIGEM IN ('WHATSAPP','IFOOD')),
  CONSTRAINT CK_DELIVERY_TAXA CHECK (VL_TAXA_ENTREGA >= 0)
) ENGINE=InnoDB;

-- =========================================================
-- 6. CANCELAMENTOS, MOVIMENTAÇÕES E AUDITORIA
-- =========================================================
CREATE TABLE IF NOT EXISTS CANCELAMENTO_DEVOLUCAO (
  ID_CANCELAMENTO INT AUTO_INCREMENT PRIMARY KEY,
  ID_VENDA INT NOT NULL,
  ID_PRODUTO INT NOT NULL,
  ID_FUNCIONARIO INT NOT NULL,
  DT_CANCELAMENTO DATETIME NOT NULL,
  DS_MOTIVO VARCHAR(255) NOT NULL,
  CONSTRAINT FK_CANCELAMENTO_VENDA FOREIGN KEY (ID_VENDA) REFERENCES VENDA(ID_VENDA),
  CONSTRAINT FK_CANCELAMENTO_PRODUTO FOREIGN KEY (ID_PRODUTO) REFERENCES PRODUTO(ID_PRODUTO),
  CONSTRAINT FK_CANCELAMENTO_FUNCIONARIO FOREIGN KEY (ID_FUNCIONARIO) REFERENCES FUNCIONARIO(ID_FUNCIONARIO)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS MOVIMENTACAO_CAIXA (
  ID_MOVIMENTACAO INT AUTO_INCREMENT PRIMARY KEY,
  ID_CAIXA INT NOT NULL,
  ID_FUNCIONARIO INT NOT NULL,
  TP_MOVIMENTACAO VARCHAR(20) NOT NULL,
  VL_VALOR DECIMAL(10,2) NOT NULL,
  DS_MOTIVO VARCHAR(255) NOT NULL,
  DT_HORA DATETIME NOT NULL,
  CONSTRAINT FK_MOV_CAIXA FOREIGN KEY (ID_CAIXA) REFERENCES CAIXA(ID_CAIXA),
  CONSTRAINT FK_MOV_FUNCIONARIO FOREIGN KEY (ID_FUNCIONARIO) REFERENCES FUNCIONARIO(ID_FUNCIONARIO),
  CONSTRAINT CK_MOV_TIPO CHECK (TP_MOVIMENTACAO IN ('SANGRIA','SUPRIMENTO')),
  CONSTRAINT CK_MOV_VALOR CHECK (VL_VALOR > 0)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS LOG_AUDITORIA (
  ID_LOG INT AUTO_INCREMENT PRIMARY KEY,
  ID_FUNCIONARIO INT NOT NULL,
  DT_HORA DATETIME NOT NULL,
  TP_ACAO VARCHAR(30) NOT NULL,
  NM_TABELA VARCHAR(60) NOT NULL,
  DS_DETALHE TEXT,
  CONSTRAINT FK_LOG_FUNCIONARIO FOREIGN KEY (ID_FUNCIONARIO) REFERENCES FUNCIONARIO(ID_FUNCIONARIO)
) ENGINE=InnoDB;

