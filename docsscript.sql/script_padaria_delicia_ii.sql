-- G22 — Quais funcionários registraram mais cancelamentos/devoluções em relação às vendas?
-- Atende: KPI de cancelamentos por funcionário; o funcionário é quem registrou a ocorrência.
SELECT f.NM_FUNCIONARIO,
       COALESCE(c.CANCELAMENTOS,0) AS CANCELAMENTOS,
       COALESCE(v.VENDAS,0) AS VENDAS,
       ROUND(100.0 * COALESCE(c.CANCELAMENTOS,0)
             / NULLIF(v.VENDAS,0),2) AS PCT_CANCELAMENTOS
FROM FUNCIONARIO f
LEFT JOIN (
    SELECT ID_FUNCIONARIO,COUNT(*) AS CANCELAMENTOS
    FROM CANCELAMENTO_DEVOLUCAO GROUP BY ID_FUNCIONARIO
) c ON c.ID_FUNCIONARIO = f.ID_FUNCIONARIO
LEFT JOIN (
    SELECT ID_FUNCIONARIO,COUNT(*) AS VENDAS
    FROM VENDA GROUP BY ID_FUNCIONARIO
) v ON v.ID_FUNCIONARIO = f.ID_FUNCIONARIO
ORDER BY CANCELAMENTOS DESC;

-- G23 — Quais caixas tiveram divergências e qual funcionário foi responsável pelo fechamento?
-- Atende: KPI de diferenças de caixa por fechamento.
SELECT c.ID_CAIXA,f.NM_FUNCIONARIO AS RESPONSAVEL_FECHAMENTO,
