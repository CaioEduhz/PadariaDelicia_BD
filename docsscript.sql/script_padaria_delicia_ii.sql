-- G24 — Quais operações críticas foram registradas por funcionário, tabela e ação?
-- Atende: KPI de auditoria de operações (últimos 30 dias).
SELECT f.NM_FUNCIONARIO,l.NM_TABELA,l.TP_ACAO,
       COUNT(*) AS OCORRENCIAS,MAX(l.DT_HORA) AS ULTIMA_OCORRENCIA
FROM LOG_AUDITORIA l
