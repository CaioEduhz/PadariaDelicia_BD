CREATE PROCEDURE GERAR_MASSA_VENDAS()
BEGIN
  DECLARE v INT DEFAULT 1;
  DECLARE v_produto INT;
  DECLARE v_cliente INT;
  DECLARE v_funcionario INT;
  DECLARE v_caixa INT;
  DECLARE v_qt DECIMAL(10,3);
  DECLARE v_preco DECIMAL(10,2);
  DECLARE v_total DECIMAL(10,2);
  DECLARE v_data DATETIME;
  DECLARE v_canal VARCHAR(20);
  DECLARE v_forma VARCHAR(30);
  DECLARE v_venda INT;

  WHILE v <= 600 DO
    SET v_produto = IF(v BETWEEN 2 AND 21, 4, MOD(v - 1, 20) + 1);
    SET v_cliente = IF(MOD(v,4) = 0, NULL, MOD(v - 1, 20) + 1);
    SET v_funcionario = IF(v = 1, 1,
      IF(MOD(v,2) = 0, 8 + MOD(v,4), 1 + MOD(v,7)));
    SET v_caixa = IF(v = 1, 5, FLOOR((v - 1) / 100) + 1);
    SET v_qt = IF(v_produto = 1, 0.250, 1.000);
    SELECT VL_PRECO_VENDA INTO v_preco
    FROM PRODUTO WHERE ID_PRODUTO = v_produto;
    SET v_total = ROUND(v_preco * v_qt, 2);
    SET v_data = IF(v = 1, '2026-11-03 10:35:00',
      TIMESTAMP(
        DATE_ADD('2026-11-01', INTERVAL FLOOR((v - 1) / 200) DAY),
        MAKETIME(6 + MOD(v,16), MOD(v * 7,60), 0)
      ));
    SET v_canal = CASE
      WHEN v = 1 THEN 'COMANDA'
      WHEN v <= 151 THEN 'DELIVERY'
      ELSE 'BALCAO'
    END;
    SET v_forma = CASE MOD(v,6)
      WHEN 0 THEN 'DINHEIRO'
      WHEN 1 THEN 'PIX'
      WHEN 2 THEN 'DEBITO'
      WHEN 3 THEN 'CREDITO'
      WHEN 4 THEN 'VALE_ALIMENTACAO'
      ELSE 'VALE_REFEICAO'
    END;

    INSERT INTO VENDA (
      ID_CAIXA,ID_FUNCIONARIO,ID_CLIENTE,ID_COMANDA,TP_CANAL,
      VL_RECEBIDO,VL_TROCO,VL_DESCONTO,DT_VENDA,TP_STATUS,
      CD_CUPOM_FISCAL,VL_TOTAL
    ) VALUES (
      v_caixa,v_funcionario,v_cliente,IF(v = 1,1,NULL),v_canal,
      v_total,0,0,v_data,'CONCLUIDA',
      CONCAT('CF-2026-',LPAD(v,6,'0')),v_total
    );
    SET v_venda = LAST_INSERT_ID();

    IF v = 1 THEN
      -- A primeira venda liquida a comanda fechada de exemplo.
      INSERT INTO ITEM_VENDA (
        ID_VENDA,ID_PRODUTO,QT_QUANTIDADE,VL_UNITARIO,VL_DESCONTO_ITEM
      )
      SELECT v_venda,ID_PRODUTO,QT_QUANTIDADE,VL_UNITARIO,0
      FROM ITEM_COMANDA
      WHERE ID_COMANDA = 1;

      SELECT COALESCE(SUM(QT_QUANTIDADE * VL_UNITARIO),0)
      INTO v_total
      FROM ITEM_COMANDA
      WHERE ID_COMANDA = 1;

      UPDATE VENDA
      SET VL_RECEBIDO = v_total, VL_TOTAL = v_total
      WHERE ID_VENDA = v_venda;
    ELSE
      INSERT INTO ITEM_VENDA (
        ID_VENDA,ID_PRODUTO,QT_QUANTIDADE,VL_UNITARIO,VL_DESCONTO_ITEM
      ) VALUES (v_venda,v_produto,v_qt,v_preco,0);

      -- Repetição controlada de cesta (coxinha + café) em 20 vendas.
      -- Isso fornece volume mínimo para a consulta de associação G29.
      IF v BETWEEN 2 AND 21 THEN
        INSERT INTO ITEM_VENDA (
          ID_VENDA,ID_PRODUTO,QT_QUANTIDADE,VL_UNITARIO,VL_DESCONTO_ITEM
        ) VALUES (v_venda,12,1.000,4.00,0);
        SET v_total = v_total + 4.00;
        UPDATE VENDA
        SET VL_RECEBIDO = v_total, VL_TOTAL = v_total
        WHERE ID_VENDA = v_venda;
      END IF;
    END IF;

    INSERT INTO PAGAMENTO_VENDA (ID_VENDA,VL_PAGO,TP_FORMA_PAGAMENTO)
    VALUES (v_venda,v_total,v_forma);

    -- Mantém exatamente 150 deliveries: vendas 2 a 151.
    IF v BETWEEN 2 AND 151 THEN
      INSERT INTO DELIVERY (
        ID_VENDA,DT_SAIDA,DT_ENTREGA,TP_STATUS,DS_OBSERVACAO,
        DS_ENDERECO_ENTREGA,TP_CANAL_ORIGEM,VL_TAXA_ENTREGA
      ) VALUES (
        v_venda,DATE_ADD(v_data,INTERVAL 10 MINUTE),
        DATE_ADD(v_data,INTERVAL 40 MINUTE),'ENTREGUE',NULL,
        CONCAT('Rua Fictícia ',v,', São Paulo - SP'),
        IF(MOD(v,2)=0,'WHATSAPP','IFOOD'),
        IF(MOD(v,2)=0,4.00,8.90)
      );
    END IF;

    SET v = v + 1;
  END WHILE;
END $$
CALL GERAR_MASSA_VENDAS() $$
