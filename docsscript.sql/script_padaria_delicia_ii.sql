-- A01 — Existem produtos vencidos que continuam ativos?
-- Verifica: RN01 (produto com validade expirada não pode ser vendido).
SELECT ID_PRODUTO,NM_PRODUTO,DT_VALIDADE
FROM PRODUTO
WHERE IN_ATIVO = TRUE AND DT_VALIDADE IS NOT NULL AND DT_VALIDADE < CURDATE();

-- A02 — Existem comandas abertas com o mesmo número?
-- Verifica: RN08 (número de comanda não pode se repetir entre comandas abertas).
SELECT NR_ABERTA,COUNT(*) AS QUANTIDADE
FROM COMANDA
WHERE TP_STATUS = 'ABERTA'
GROUP BY NR_ABERTA
HAVING COUNT(*) > 1;

-- A03 — Existem encomendas com sinal inferior a 20% do total?
-- Verifica: RN05/RN17 (sinal mínimo de 20% para confirmar encomenda).
SELECT ID_ENCOMENDA,VL_TOTAL,VL_SINAL
FROM ENCOMENDA
WHERE VL_SINAL < ROUND(VL_TOTAL * 0.20,2)
  AND TP_STATUS <> 'CANCELADA';

-- A04 — Existem vendas concluídas sem cupom fiscal registrado?
-- Verifica: RN10 (registro obrigatório do documento fiscal da venda).
SELECT ID_VENDA,DT_VENDA,VL_TOTAL
FROM VENDA
WHERE TP_STATUS = 'CONCLUIDA'
  AND (CD_CUPOM_FISCAL IS NULL OR CD_CUPOM_FISCAL = '');

-- A05 — Existem vendas sem nenhum item registrado?
-- Verifica: RN04 (rastreabilidade dos itens vinculados à transação).
SELECT v.ID_VENDA
FROM VENDA v
LEFT JOIN ITEM_VENDA i ON i.ID_VENDA = v.ID_VENDA
WHERE i.ID_ITEM IS NULL;

-- A06 — O total da venda corresponde à soma dos itens?
-- Verifica: RN14 (consistência entre total da venda e itens registrados).
SELECT v.ID_VENDA,v.VL_TOTAL,
       COALESCE(SUM(i.QT_QUANTIDADE * i.VL_UNITARIO - i.VL_DESCONTO_ITEM),0) AS TOTAL_ITENS
FROM VENDA v
LEFT JOIN ITEM_VENDA i ON i.ID_VENDA = v.ID_VENDA
WHERE v.TP_STATUS = 'CONCLUIDA'
GROUP BY v.ID_VENDA,v.VL_TOTAL
HAVING ABS(v.VL_TOTAL - TOTAL_ITENS) > 0.01;

-- A07 — A soma dos pagamentos corresponde ao total das vendas concluídas?
-- Verifica: RN14 (pagamento integral, inclusive quando dividido em formas distintas).
SELECT v.ID_VENDA,v.VL_TOTAL,COALESCE(SUM(p.VL_PAGO),0) AS TOTAL_PAGO
FROM VENDA v
LEFT JOIN PAGAMENTO_VENDA p ON p.ID_VENDA = v.ID_VENDA
WHERE v.TP_STATUS = 'CONCLUIDA'
GROUP BY v.ID_VENDA,v.VL_TOTAL
HAVING ABS(v.VL_TOTAL - TOTAL_PAGO) > 0.01;

-- A08 — Existem deliveries vinculados a vendas de outro canal?
-- Verifica: RN13 (coerência do registro de delivery e sua origem).
SELECT d.ID_DELIVERY,v.ID_VENDA,v.TP_CANAL
FROM DELIVERY d
JOIN VENDA v ON v.ID_VENDA = d.ID_VENDA
WHERE v.TP_CANAL <> 'DELIVERY';

-- A09 — Existem produtos com saldo ou estoque mínimo negativo?
-- Verifica: RN02 (integridade do estoque); os CHECKs também impedem esses valores.
SELECT ID_PRODUTO,NM_PRODUTO,QT_ESTOQUE,QT_ESTOQUE_MINIMO
FROM PRODUTO
WHERE QT_ESTOQUE < 0 OR QT_ESTOQUE_MINIMO < 0;

-- A10 — Existem contas pagas sem data de pagamento ou com data em conta não paga?
-- Verifica: RN06 (rastreabilidade e consistência das contas a pagar).
SELECT ID_CONTA_PAGAR,TP_STATUS,DT_PAGAMENTO
FROM CONTA_PAGAR
WHERE (TP_STATUS = 'PAGA' AND DT_PAGAMENTO IS NULL)
   OR (TP_STATUS <> 'PAGA' AND DT_PAGAMENTO IS NOT NULL);

-- A11 — Existem comandas fechadas sem venda correspondente?
-- Verifica: RN04 (rastreabilidade do atendimento e respectiva venda).
SELECT cm.ID_COMANDA,cm.NR_COMANDA,cm.DT_FECHAMENTO
FROM COMANDA cm
LEFT JOIN VENDA v ON v.ID_COMANDA = cm.ID_COMANDA
WHERE cm.TP_STATUS = 'FECHADA' AND v.ID_VENDA IS NULL;

-- A12 — Existem pagamentos com forma fora do domínio permitido?
-- Verifica: RN14 (formas de pagamento permitidas e pagamentos mistos).
SELECT ID_PAGAMENTO,ID_VENDA,TP_FORMA_PAGAMENTO
FROM PAGAMENTO_VENDA
WHERE TP_FORMA_PAGAMENTO NOT IN
 ('DINHEIRO','PIX','DEBITO','CREDITO','VALE_ALIMENTACAO','VALE_REFEICAO');

-- A13 — A diferença registrada corresponde ao valor informado menos o valor do sistema?
-- Verifica: RN07/RN18 (conferência e fechamento de caixa por turno).
SELECT ID_CAIXA,VL_TOTAL_SISTEMA,VL_TOTAL_INFORMADO,VL_DIFERENCA
FROM CAIXA
WHERE TP_STATUS = 'FECHADO'
  AND ABS(VL_DIFERENCA - (VL_TOTAL_INFORMADO - VL_TOTAL_SISTEMA)) > 0.01;

-- A14 — Existem deliveries marcados como entregues sem data de saída ou entrega?
-- Verifica: RN13 (registro consistente de saída e entrega).
SELECT ID_DELIVERY,TP_STATUS,DT_SAIDA,DT_ENTREGA
FROM DELIVERY
WHERE TP_STATUS = 'ENTREGUE'
  AND (DT_SAIDA IS NULL OR DT_ENTREGA IS NULL);

-- A15 — Existem itens de compra sem exatamente um tipo de item?
-- Verifica: RN24 (exclusividade do tipo de item na compra).
SELECT ID_ITEM,ID_COMPRA,ID_PRODUTO,ID_MATERIA_PRIMA
FROM ITEM_COMPRA
WHERE (ID_PRODUTO IS NULL AND ID_MATERIA_PRIMA IS NULL)
   OR (ID_PRODUTO IS NOT NULL AND ID_MATERIA_PRIMA IS NOT NULL);

